def normalize_item(raw: dict) -> dict:
    price_czk = raw.get("price_czk")
    price_eur = raw.get("price_eur")
    if price_eur is None and price_czk is not None:
        price_eur = round(price_czk / CZK_PER_EUR)
    was = raw.get("price_was_czk")
    disc = None
    if was and price_czk and was > price_czk:
        disc = round(100 * (1 - price_czk / was))
    over = bool(raw.get("over_budget")) or (price_czk is not None and price_czk > 50000)
    return {
        "title": raw["title"],
        "url": raw["url"],
        "source": raw["source"],
        "location": raw.get("location") or "",
        "year": raw.get("year"),
        "fit": raw.get("fit") or "?",
        "color": raw.get("color") or "",
        "price_czk": price_czk,
        "price_eur": price_eur,
        "price_was_czk": was,
        "discount_pct": disc,
        "spec": raw.get("spec") or "",
        "notes": list(raw.get("notes") or []),
        "over_budget": over,
        "image_url": raw.get("image_url"),
        "score": 0,
    }
